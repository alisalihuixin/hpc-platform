/**
 * Regenerate the typed API client from the live OpenAPI schema.
 *
 *   npm run gen:api
 *   OPENAPI_URL=http://localhost:8000/openapi.json npm run gen:api
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

import openapiTS, { astToString } from 'openapi-typescript';

const source = process.env.OPENAPI_URL ?? 'http://localhost:8000/openapi.json';
const output = path.resolve(process.cwd(), 'src/lib/api/schema.d.ts');

// Accept a local file too, so the schema can be regenerated without running the
// API: `OPENAPI_URL=../api/openapi.json npm run gen:api`.
const isRemote = source.startsWith('http://') || source.startsWith('https://');
const input = isRemote
  ? new URL(source)
  : await readFile(path.resolve(process.cwd(), source));
const ast = await openapiTS(input);
await writeFile(
  output,
  `/**\n * AUTO-GENERATED by scripts/gen-api.mjs - do not edit by hand.\n * Source: ${source}\n */\n${astToString(ast)}`,
  'utf8',
);

console.log(`generated ${path.relative(process.cwd(), output)} from ${source}`);
