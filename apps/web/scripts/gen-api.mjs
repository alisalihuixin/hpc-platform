/**
 * Regenerate the typed API client from the live OpenAPI schema.
 *
 *   npm run gen:api
 *   OPENAPI_URL=http://localhost:8000/openapi.json npm run gen:api
 */
import { writeFile } from 'node:fs/promises';
import path from 'node:path';

import openapiTS, { astToString } from 'openapi-typescript';

const url = process.env.OPENAPI_URL ?? 'http://localhost:8000/openapi.json';
const output = path.resolve(process.cwd(), 'src/lib/api/schema.d.ts');

const ast = await openapiTS(new URL(url));
await writeFile(
  output,
  `/**\n * AUTO-GENERATED by scripts/gen-api.mjs - do not edit by hand.\n * Source: ${url}\n */\n${astToString(ast)}`,
  'utf8',
);

console.log(`generated ${path.relative(process.cwd(), output)} from ${url}`);
